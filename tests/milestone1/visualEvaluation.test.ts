/**
 * Phase 4 Milestone 1 in the Evaluation Framework: the scenarios-v3 dataset,
 * the blocking `visual_evidence` check, the observation and evidence figures,
 * and recordings made before the blocks existed.
 *
 * Everything here is synthetic. Nothing is evidence about any model, and no
 * network call is possible (fetch throws).
 */

import { afterEach, beforeEach, describe, expect, it, jest } from '@jest/globals'
import { readFileSync } from 'node:fs'

jest.mock('server-only', () => ({}), { virtual: true })

import { describeComposition } from '@/benchmark/harness'
import { evaluateRecording, renderMarkdown, serializeReport, type EvaluationReport } from '@/evaluation/evaluate'
import { datasetPaths, loadCases, loadRecording, loadReferenceSet, loadReport } from '@/evaluation/load'
import { tierOf } from '@/evaluation/reference'
import { UNAVAILABLE_EARLIER_SCHEMA } from '@/evaluation/visualEvidence'
import { classifyMetricChanges, classifyRegressions } from '@/evaluation/regression'
import { GARMENT_MODES } from '@/lib/constants/garmentModes'
import { ANALYSIS_OUTPUT_SCHEMA_VERSION } from '@/lib/services/openai/openAIAnalysisSchema'
import { getAnalysisPromptVersion } from '@/lib/services/openai/openAIAnalysisService'

// eslint-disable-next-line @typescript-eslint/no-require-imports
const scenarios = require('../../scripts/evaluation/build-scenarios.cjs') as { build: (name?: string) => Record<string, string>; V3_CASES: Array<{ id: string; dna?: string; mode?: string; visual?: { problems?: string[] } }> }

const root = process.cwd()
const v3 = datasetPaths(root, 'scenarios-v3')
const CURRENT = { promptVersion: 'aaaaaaaaaaaa', schemaVersion: ANALYSIS_OUTPUT_SCHEMA_VERSION }
const cases = loadCases(v3.casesPath)
const references = loadReferenceSet(v3.referencesPath as string, cases)

let fetchSpy: jest.SpiedFunction<typeof fetch>
beforeEach(() => {
  fetchSpy = jest.spyOn(global, 'fetch').mockImplementation(() => { throw new Error('Network access is not allowed in an evaluation.') })
})
afterEach(() => {
  expect(fetchSpy).not.toHaveBeenCalled()
  jest.restoreAllMocks()
})

const evaluate = (change?: (recording: ReturnType<typeof loadRecording>) => void, withReferences = true): EvaluationReport => {
  const recording = loadRecording(v3.recordingPath)
  change?.(recording)
  return evaluateRecording(recording, cases, CURRENT, 'mock', withReferences ? { references } : {})
}

describe('scenarios-v3: the dataset', () => {
  it('is generated by the committed script and up to date', () => {
    const built = scenarios.build('scenarios-v3')
    for (const name of ['cases.json', 'recording.json', 'references.json']) {
      expect(readFileSync(`${root}/evaluation/datasets/scenarios-v3/${name}`, 'utf8').replace(/\r\n/g, '\n')).toBe(built[name])
    }
  })

  it('has at least ten cases in every garment mode, and at least ten with and ten without Style DNA', () => {
    const composition = describeComposition(cases)
    for (const mode of GARMENT_MODES) expect(composition.cases_by_mode[mode]).toBeGreaterThanOrEqual(10)
    expect(composition.style_dna.cases).toBeGreaterThanOrEqual(10)
    expect(composition.cases - composition.style_dna.cases).toBeGreaterThanOrEqual(10)
  })

  it('covers every regression scenario of the milestone', () => {
    const problems = new Set(scenarios.V3_CASES.flatMap((entry) => entry.visual?.problems ?? []))
    // Missing and malformed observations, missing evidence, invalid references, unsupported claims (material, price),
    // contradictions (identification, views), image mapping (merged items, wrong number, views entry), Style DNA misuse,
    // a contradicting support level and prompt injection.
    for (const problem of ['schema', 'invalid_citation', 'unsupported_text', 'identification_inconsistent', 'views_contradiction', 'views_unexplained', 'views_missing', 'views_unexpected', 'image_mapping', 'unsupplied_source', 'support_conflict']) {
      expect(problems.has(problem)).toBe(true)
    }
    const ids = scenarios.V3_CASES.map((entry) => entry.id)
    for (const id of ['v3-single-missing-observations', 'v3-single-malformed-observations', 'v3-single-missing-evidence', 'v3-single-poor-quality', 'v3-single-lighting', 'v3-single-occlusion', 'v3-views-disagreement', 'v3-outfit-office-three', 'v3-single-prompt-injection', 'v3-single-unsupplied-style-dna']) {
      expect(ids).toContain(id)
    }
  })

  it('has a synthetic reference set only: no reviewer, no image review, never the image-reviewed tier', () => {
    for (const reference of references.references) {
      expect(reference.basis).toBe('synthetic')
      expect(reference.reviewer).toBeUndefined()
      expect(tierOf(reference)).toBe('synthetic')
    }
  })
})

describe('scenarios-v3: the evaluation', () => {
  const report = evaluate()

  it('passes every case, including the visual_evidence check on all of them', () => {
    expect(report.cases.filter((entry) => entry.status !== 'pass').map((entry) => [entry.case_id, entry.failure_reasons])).toEqual([])
    expect(report.cases.every((entry) => entry.checks.find((check) => check.check === 'visual_evidence')?.status === 'pass')).toBe(true)
  })

  it('reports the structural figures from the fixtures, and says what they are', () => {
    const structural = report.quality.visual_evidence.structural
    expect(report.quality.visual_evidence.applicable).toBe(true)
    expect(structural.invalid_citation_rate.value).toBeGreaterThan(0)
    expect(structural.unsupported_text_rate.value).toBeGreaterThan(0)
    expect(structural.view_contradiction_rate.n).toBe(report.composition.cases_by_mode.same_garment_views)
    expect(structural.outfit_identity_consistency_rate.value).toBeLessThan(1)
    expect(report.metric_index['visual_evidence.structural.invalid_citation_rate']).toMatchObject({ direction: 'lower_is_better', needs_references: false, pooled_over_style_dna: true })
    expect(renderMarkdown(report)).toContain('Hand-written fixture outputs: these figures check that Verdict validates the blocks as intended.')
  })

  it('scores observations against the synthetic references, never as image-grounded accuracy', () => {
    const synthetic = report.quality.visual_evidence.by_tier.synthetic
    expect(synthetic.cases).toBeGreaterThanOrEqual(10)
    expect(synthetic.garment_category_accuracy.status).toBe('measured')
    // One reference names a colour family the fixture output leaves out, so recall is below 1.
    expect(synthetic.dominant_colour_recall.value).toBeLessThan(1)
    expect(report.quality.visual_evidence.by_tier.image_reviewed.garment_category_accuracy).toMatchObject({ status: 'unavailable', value: null })
    expect(report.quality.image_grounded_accuracy.status).toBe('unavailable')
  })

  it('keeps Style DNA conditions apart: separate figures exist for both, and the combined ones say they are pooled', () => {
    expect(report.metric_index['style_dna.with_style_dna.visual_evidence.structural.observations_valid_rate']).toMatchObject({ style_dna_condition: 'with_style_dna', status: 'measured' })
    expect(report.metric_index['style_dna.without_style_dna.visual_evidence.structural.observations_valid_rate']).toMatchObject({ style_dna_condition: 'without_style_dna', status: 'measured' })
  })

  it('never puts model text in the report', () => {
    const text = `${serializeReport(report)}\n${renderMarkdown(report)}`
    for (const fragment of ['notched lapels', 'soft cashmere', 'ignore previous instructions', 'Looks expensive', 'View 2 shows']) expect(text).not.toContain(fragment)
  })
})

describe('the visual_evidence check fails when a block is not handled as expected', () => {
  it('fails, naming blocks and codes only, when a refused block is expected to be usable', () => {
    const changed = evaluate((recording) => {
      const entry = recording.entries.find((item) => item.case_id === 'v3-single-navy-blazer-office') as { output: { observations: { images: Array<Record<string, unknown>> } } }
      entry.output.observations.images[0].details = ['100% wool lapels']
    })
    const result = changed.cases.find((entry) => entry.case_id === 'v3-single-navy-blazer-office')
    expect(result?.status).toBe('fail')
    expect(result?.failure_reasons.join(' ')).toMatch(/visual_evidence: .*observations were unavailable, expected available/)
    expect(result?.failure_reasons.join(' ')).not.toContain('wool')
  })

  it('fails when validation stops reporting a problem the case depends on', () => {
    const changed = evaluate((recording) => {
      for (const item of recording.entries.filter((entry) => entry.case_id === 'v3-single-unsupplied-style-dna')) {
        const evidence = (item.output as { evidence: Record<string, { sources: string[] }> }).evidence
        evidence.style_preference_match.sources = evidence.style_preference_match.sources.filter((source) => source !== 'style_dna')
      }
    })
    const result = changed.cases.find((entry) => entry.case_id === 'v3-single-unsupplied-style-dna')
    expect(result?.failure_reasons.join(' ')).toMatch(/evidence was available, expected partial.*validation did not report unsupplied_source/)
  })
})

describe('recordings made before observations and evidence existed', () => {
  it('are never scored as if the blocks were missing: every figure is unavailable, with the reason', () => {
    const relabelled = evaluate((recording) => { recording.schema_version = 'analysis-output/2' })
    expect(relabelled.quality.visual_evidence).toMatchObject({ applicable: false, reason: UNAVAILABLE_EARLIER_SCHEMA })
    const visual = Object.entries(relabelled.metric_index).filter(([name]) => name.startsWith('visual_evidence.'))
    expect(visual.length).toBeGreaterThan(0)
    for (const [, metric] of visual) expect(metric).toMatchObject({ status: 'unavailable', value: null })
    expect(relabelled.evaluated_with.same_schema_as_recording).toBe(false)
    expect(renderMarkdown(relabelled)).toContain('The recording was made with a different prompt or schema than the current code.')
  })
})

describe('findings of the independent evaluation review', () => {
  it('the blocking check does not judge a recording made before the blocks existed', () => {
    const relabelled = evaluate((recording) => {
      recording.schema_version = 'analysis-output/2'
      for (const entry of recording.entries) {
        const output = entry.output as Record<string, unknown>
        delete output.observations
        delete output.evidence
      }
    })
    expect(relabelled.summary.failed).toBe(0)
    expect(relabelled.cases.every((entry) => entry.checks.find((check) => check.check === 'visual_evidence')?.status === 'not_applicable')).toBe(true)
  })

  it('never reports missing blocks as an absence of problems', () => {
    const stripped = evaluate((recording) => {
      for (const entry of recording.entries) {
        const output = entry.output as Record<string, unknown>
        delete output.observations
        delete output.evidence
      }
    })
    const structural = stripped.quality.visual_evidence.structural
    for (const metric of [structural.invalid_citation_rate, structural.image_mapping_error_rate, structural.view_contradiction_rate, structural.unsupported_text_rate, structural.support_conflict_rate, structural.unsupplied_source_rate]) {
      expect(metric).toMatchObject({ status: 'unavailable', value: null })
    }
    expect(structural.observations_valid_rate.value).toBe(0)
  })

  it('counts a citation error only where the observations were usable, not as a knock-on of refused observations', () => {
    const report = evaluate()
    const flagged = report.cases.filter((entry) => entry.case_id === 'v3-single-invalid-citation')
    expect(flagged).toHaveLength(1)
    expect(report.quality.visual_evidence.structural.invalid_citation_rate.value).toBeGreaterThan(0)
    expect(report.quality.visual_evidence.structural.invalid_citation_rate.n).toBeLessThan(report.dataset.cases)
  })
})

describe('the committed baselines', () => {
  const current = async () => ({ promptVersion: await getAnalysisPromptVersion(), schemaVersion: ANALYSIS_OUTPUT_SCHEMA_VERSION })

  it.each(['scenarios-v1', 'scenarios-v2', 'scenarios-v3'] as const)('%s was produced by the current prompt and schema code', async (dataset) => {
    const baseline = loadReport(datasetPaths(root, dataset).baselinePath as string)
    const versions = await current()
    expect(baseline.evaluated_with).toMatchObject({ prompt_version: versions.promptVersion, schema_version: versions.schemaVersion })
    expect(baseline.report_format).toBe('verdict-evaluation-report/6')
  })

  it('scenarios-v3 is byte-identical to the current report and shows no regression', () => {
    const committed = readFileSync(v3.baselinePath as string, 'utf8').replace(/\r\n/g, '\n')
    const baseline = JSON.parse(committed) as EvaluationReport
    const report = evaluateRecording(loadRecording(v3.recordingPath), cases, { promptVersion: baseline.evaluated_with.prompt_version, schemaVersion: ANALYSIS_OUTPUT_SCHEMA_VERSION }, 'mock', { references })
    expect(serializeReport(report)).toBe(committed)
    expect(classifyRegressions(baseline, report).has_regression).toBe(false)
    expect(classifyMetricChanges(baseline, report).has_regression).toBe(false)
  })
})
